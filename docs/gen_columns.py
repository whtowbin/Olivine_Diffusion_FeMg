"""Write the documentation site's column reference (docs/site/columns.md).

The tables come from `forster.template` (the same text `forster template` writes as
COLUMNS.md and the README holds), so the page cannot drift from the code:
tests/test_docs.py fails when the committed page differs from `columns_page()`.

    uv run python docs/gen_columns.py          # rewrite the page
    uv run python docs/gen_columns.py --check  # exit 1 if it is out of date
"""

from __future__ import annotations

import sys
from pathlib import Path

from forster.template import (
    DIFFUSIVITY_COLUMNS,
    DIFFUSIVITY_EQUATION,
    PARAMETER_COLUMNS,
    PROFILE_COLUMNS,
    SUMMARY_COLUMNS,
    column_table,
)

PAGE = Path(__file__).resolve().parent / "site" / "columns.md"

INTRO = """\
# Column reference

<!-- Generated by docs/gen_columns.py from forster.template; do not edit by hand.
     Rerun `uv run python docs/gen_columns.py` after changing a column. -->

Every column FORSTER reads or writes, generated from the code
(`forster.template`). `forster template` writes the same tables into your folder as
`COLUMNS.md`. Fo is a fraction throughout (0.895, not 89.5); the desktop app shows
it in mol% and converts.

**Needed** says whether a column must be filled: *required*, *optional*, or *one
form*. Give fO2 either as `fO2_Pa` or as `fO2_buffer` with `fO2_delta_log`, and the
orientation either as `alpha_deg`, `beta_deg`, `gamma_deg` or as the four EBSD
columns (`phi1_deg`, `Phi_deg`, `phi2_deg`, `profile_angle_deg`). Leave the other
form empty.

Columns that hold several values (one per step, per segment or per growth stage)
take them in quotes, separated by commas: `"0.91, 0.89"`. An empty entry in such a
list (`"0.002, , 0.003"`) means "none for this one".

The pages [Setting up a run](setup.md) and [Reading the results](results.md) explain
what the columns change and how to read them.
"""


def columns_page() -> str:
    """The text of docs/site/columns.md."""
    parts = [
        INTRO,
        "## profiles.csv\n\nOne row per analysis point.",
        column_table(PROFILE_COLUMNS),
        "## parameters.csv\n\nOne row per model run (one fit of one profile).",
        column_table(PARAMETER_COLUMNS),
        "## diffusivities.csv\n\n"
        "Optional: your own diffusivity equations, one row per equation, named in the "
        "`diffusivity` column of parameters.csv and passed to `forster fit` with "
        "`--diffusivities`. For each crystal axis i ([100], [010], [001]):\n\n"
        f"`{DIFFUSIVITY_EQUATION}`\n\n"
        "with T in K, P and fO2 in Pa and R = 8.3145 J/mol/K. Along the profile, D is "
        "the sum of D_i cos²(angle to axis i). The table `forster template` writes "
        "holds the built-in equations; copy a row, give it a new name and change the "
        "values.",
        column_table(DIFFUSIVITY_COLUMNS),
        "## summary.csv\n\n"
        "Written by `forster fit` (and by the app's Export): one row per fitted run, "
        "with `run`, `profile`, the results below and every parameter column above "
        "(fO2 in Pa, orientation as angles), so it can be read back as a parameter "
        "table to repeat the fits.",
        column_table(SUMMARY_COLUMNS),
    ]
    return "\n\n".join(parts) + "\n"


def main(argv: list[str]) -> int:
    text = columns_page()
    if "--check" in argv:
        current = PAGE.read_text(encoding="utf-8") if PAGE.exists() else ""
        if current != text:
            print(f"{PAGE} is out of date; run: uv run python docs/gen_columns.py")
            return 1
        return 0
    PAGE.write_text(text, encoding="utf-8")
    print(f"wrote {PAGE}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
